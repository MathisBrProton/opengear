export function t(fr) {
  if (fr == null) return fr;
  const raw = String(fr);
  if (curLang() !== "en") return raw;
  const trimmed = raw.trim();
  if (!trimmed) return raw;
  if (EN[trimmed]) return raw.replace(trimmed, EN[trimmed]);
  for (const [re, fmt] of REGEX_MAP) {
    const m = trimmed.match(re);
    if (m) return raw.replace(trimmed, fmt(...m));
  }
  return raw;
}

/** Update static sidebar, footer and <html lang> according to active language. */
export function translateChrome() {
  const isEn = curLang() === "en";
  document.documentElement.lang = isEn ? "en" : "fr";
  const navEn = {
    home: "Home", lighting: "Lighting", performance: "Performance",
    input: "Keys & Macros", profiles: "Profiles", devices: "Devices", system: "System",
  };
  const navFr = {
    home: "Accueil", lighting: "Éclairage", performance: "Performances",
    input: "Touches & Macros", profiles: "Profils", devices: "Appareils", system: "Système",
  };
  document.querySelectorAll(".nav-item").forEach((b) => {
    const sp = b.querySelector("span:not(.nav-badge)");
    if (sp && b.dataset.tab) sp.textContent = (isEn ? navEn : navFr)[b.dataset.tab] || sp.textContent;
  });
  const lblProf = document.querySelector('label[for="profile-select"]');
  if (lblProf) lblProf.textContent = isEn ? "Active profile" : "Profil actif";
  const lblMode = document.getElementById("mode-label");
  if (lblMode) lblMode.textContent = isEn ? "Display mode" : "Mode d'affichage";
  const verEl = document.getElementById("app-version");
  if (verEl && S && S.app_version) {
    verEl.textContent = isEn
      ? `OpenGear v${S.app_version} · no telemetry`
      : `OpenGear v${S.app_version} · aucune télémétrie`;
  }
  const mh = document.getElementById("mode-hint");
  if (mh && S) {
    const mode = ui().mode;
    mh.textContent = isEn
      ? (mode === "simple" ? "Advanced settings hidden." : "All settings visible.")
      : (mode === "simple" ? "Réglages avancés masqués." : "Tous les réglages sont visibles.");
  }
  const ub = document.getElementById("btn-undo");
  if (ub && S) {
    ub.textContent = S.undo_label
      ? (isEn ? `Undo: ${t(S.undo_label)}` : `Annuler : ${S.undo_label}`)
      : (isEn ? "Undo last change" : "Annuler la dernière modification");
    ub.title = ub.textContent;
  }
  const bs = document.getElementById("badge-system");
  if (bs && bs.title) {
    bs.title = t(bs.title);
  }
}

/** Translate visible text nodes and attributes inside `root` when UI language is English. */
export function translateDom(root) {
  if (!root || curLang() !== "en") return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement && node.parentElement.closest("code, pre, .mono.selectable")) continue;
    const next = t(node.nodeValue);
    if (next !== node.nodeValue) node.nodeValue = next;
  }
  root.querySelectorAll("[title], [aria-label], [placeholder]").forEach((el) => {
    if (el.title) el.title = t(el.title);
    const al = el.getAttribute("aria-label");
    if (al) el.setAttribute("aria-label", t(al));
    const ph = el.getAttribute("placeholder");
    if (ph) el.setAttribute("placeholder", t(ph));
  });
}
